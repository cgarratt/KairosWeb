const assert=require('assert');const fs=require('fs');const path=require('path');const vm=require('vm');
vm.runInThisContext(fs.readFileSync(path.join(__dirname,'../static/purchase_plan.js'),'utf8'));
const {calculate}=require('../static/o2_sequential.js');
const tokens=[{token:'A',price:100,current_usdt:200,target:0.2},{token:'B',price:100,current_usdt:800,target:0.8}];
const levels={A:{ref382:90,c1:80,c2:70,ref786:60},B:{ref382:90,c1:80,c2:70,ref786:60}};
const fallback={requireEligibility:true,eligibility:{A:true,B:false},weightsByToken:{A:[20,30,40,10],B:[30,30,20,20]}};
const a=calculate(tokens,levels,[20,30,40,10],1000,1,fallback);
assert(a.spent>0 && a.spent<=200+1e-7,`Only available INFRA deficit can be used, spent ${a.spent}`);
assert(a.totalByToken[1]===0, 'Structurally blocked B must receive $0');
assert(a.prices[1].every(x=>x===null),'Blocked B must have no actionable Fibo levels');
assert(a.consumed.every((v,j)=>v<=a.stageBudgets[j]+1e-7), 'No tranche may exceed its theoretical 100% envelope');
assert(Math.abs(a.stageBudgets.reduce((s,v)=>s+v,0)-1000)<1e-7, 'The four tranches use 100% of the chosen slider budget');
assert(Math.abs(a.unallocated+a.spent-1000)<1e-7, 'No invented fills or missing cash');
assert(a.stageBudgets[0]>200,'Blocked tokens must NOT diminish the selected budget');
assert(a.cash>=800 && Math.abs(a.cash+a.spent-1000)<1e-7);
const blocked=calculate(tokens,levels,[20,30,40,10],1000,1,{requireEligibility:true});
assert(blocked.spent===0,'Omitted eligibility must fail closed');
assert(Math.abs(blocked.stageBudgets.reduce((v,x)=>v+x,0)-1000)<1e-7, 'Blocked tokens cannot modify slider budget allocation');
assert(Math.abs(blocked.unallocated-1000)<1e-7,'If no candidate qualifies, 100% remains physically in USDT');
assert(blocked.cash===1000);
const o4=calculate(tokens,levels,[20,30,40,10],1000,1,{...fallback,weightsByToken:{A:[30,30,20,20]}});
assert(o4.consumed.every((v,j)=>v<=o4.stageBudgets[j]+1e-7));
assert(Math.abs(o4.stageBudgets.reduce((s,v)=>s+v,0)-1000)<1e-7);
const common=calculate(tokens,levels,[20,30,40,10],1000,1,{requireEligibility:true,eligibility:{A:true,B:true}});
assert(Math.abs(common.stageBudgets.reduce((v,x)=>v+x,0)-1000)<1e-7);
assert(common.consumed.every((v,j)=>v<=common.stageBudgets[j]+1e-7));
assert(common.spent<=1000+1e-7);
console.log('Web Compras budget 100% tranches and INFRA-only PASS');
